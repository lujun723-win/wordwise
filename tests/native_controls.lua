-- Actual KOReader widgets, glyph rasterization and touch slider callbacks.
require("setupkoenv")
local root,output=assert(arg[1]),assert(arg[2])
package.path=root.."/wordwise.koplugin/?.lua;"..package.path
G_defaults=require("luadefaults"):open()
G_reader_settings=require("luasettings"):open(os.getenv("KO_HOME").."/settings.reader.lua")
local Device=require("device")
require("document/canvascontext"):init(Device)
local BB,Font=require("ffi/blitbuffer"),require("ui/font")
local Label,Text=require("wordwise_label"),require("wordwise_text")
local face=Font:getFace("cfont",8)
local label=Label.new("秘密",face)
local measured=label:getSize()
assert(measured.h<math.ceil(face.ftsize:getHeightAndAscender()),"font blank leading was retained")
local bitmap=BB.new(240,100,BB.TYPE_BB8)
bitmap:paintRect(0,0,240,100,BB.COLOR_WHITE);label:paintTo(bitmap,10,10)
local ink=assert(Text.inkBounds(bitmap,{x=0,y=0,w=240,h=100}))
assert(ink.x0==10 and ink.y0==10 and ink.x1==10+measured.w and ink.y1==10+measured.h)
label:free();bitmap:free()
local WordWise=assert(loadfile(root.."/wordwise.koplugin/main.lua"))()
local settings=require("luasettings"):wrap({})
local o=setmetatable({threshold=2,enabled=false,show_button=true,labels={},generation=0,settings=settings,
    view={footer_visible=true,footer={getHeight=function() return 70 end}},
    ui={document={info={has_pages=true}},dialog=require("ui/widget/container/widgetcontainer"):new{}}},{__index=WordWise})
local rect=o:buttonRect()
assert(rect.y+rect.h<Device.screen:getHeight()-70)
o.font_size,o.limit=8,30
o:layoutHints({{word="secret",gloss="秘密",x0=100,x1=180,y0=123,y1=163,line_id=2,level=2,rank=1}},
    {{x0=20,x1=1000,y0=50,y1=94},{x0=20,x1=1000,y0=123,y1=163}})
assert(#o.labels==1,"29px gap should fit actual glyphs and overbrace at unchanged 8pt")
o:releaseLabels()
local background=BB.new(Device.screen:getWidth(),Device.screen:getHeight(),BB.TYPE_BB8)
background:paintRect(0,0,background:getWidth(),background:getHeight(),BB.Color8(180))
o:paintTo(background,0,0)
assert(background:getPixel(rect.x,rect.y):getColor8().a==180,"button background is not transparent")
assert(background:getPixel(rect.x+rect.w-1,rect.y+rect.h-1):getColor8().a==180,"button still has a border")
background:free()
o:onWordWiseSettings();local dialog=assert(o.controls)
local slider=dialog._added_widgets[4]
slider.scroll_callback(0);slider.scroll_callback(1)
assert(slider.low==5/6 and slider.high==1)
local image=BB.new(Device.screen:getWidth(),Device.screen:getHeight(),BB.TYPE_BB8)
image:paintRect(0,0,image:getWidth(),image:getHeight(),BB.COLOR_WHITE)
dialog:paintTo(image,0,0);assert(image:writePNG(output..".png"));image:free()
slider:onPanScroll(nil,{pos={x=slider.touch_dimen.x+slider.width/2}})
assert(slider.low==3/6,"native drag did not select CET4")
slider.scroll_callback(1)
dialog.buttons[1][2].callback()
assert(o.controls==nil and o.threshold==5 and settings:readSetting("threshold")==5 and o.enabled==false)
o:onWordWiseSettings();dialog=assert(o.controls)
dialog._added_widgets[1].checked=true
dialog._added_widgets[1].callback()
dialog.buttons[1][2].callback()
assert(o.enabled==true and o.auto_task)
o:setEnabled(false)
local Dispatcher=require("dispatcher")
Dispatcher:init();o:onDispatcherRegisterActions()
local Gestures=assert(loadfile("plugins/gestures.koplugin/main.lua"))()
local native_gestures=setmetatable({gestures={},defaults={}}, {__index=Gestures})
o.ui.gestures=native_gestures
local menu=o:gestureMenu()
local editor=menu[2].sub_item_table_func()
assert(#editor>2 and next(native_gestures.gestures)==nil,"native editor must preserve assignments")
o.button_text:free()
print("1 passed, 0 failed; actual glyph crop and slider dialog")
