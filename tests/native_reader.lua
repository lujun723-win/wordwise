-- Whole ReaderUI lifecycle: real touch dispatch, popup and automatic page update.
require("setupkoenv")
local root=assert(os.getenv("WORDWISE_PROJECT"))
local book=root.."/tests/fixtures/reader-pages.html"
G_defaults=require("luadefaults"):open()
G_reader_settings=require("luasettings"):open(os.getenv("KO_HOME").."/settings.reader.lua")
local UIManager=require("ui/uimanager")
UIManager:scheduleIn(1,function()
    local ui=assert(require("apps/reader/readerui").instance,"reader did not open")
    local plugin=assert(ui.wordwise,"plugin did not load")
    plugin:saveOption("show_button",true)
    ui.rolling:onGotoPage(1)
    local rect=plugin:buttonRect()
    ui:onGesture({ges="tap",pos=require("ui/geometry"):new{x=rect.x+rect.w/2,y=rect.y+rect.h/2}})
    assert(plugin.controls,"button tap was consumed by page turn")
    require("ui/uimanager"):close(plugin.controls)
    local old_spacing=ui.document.configurable.line_spacing
    plugin:setEnabled(true)
    assert(ui.document.configurable.line_spacing==200,"native line spacing did not maximize")
    UIManager:scheduleIn(2,function()
        assert(#plugin.labels>0,"auto mode did not scan current page")
        local first=ui.document:getCurrentPage()
        ui.rolling:onGotoViewRel(1)
        assert(ui.document:getCurrentPage()>first,"fixture did not turn page")
        UIManager:scheduleIn(2,function()
            assert(#plugin.labels>0,"auto mode did not scan next page")
            local changed=false
            for _,label in ipairs(plugin.labels) do
                assert(label.hint.word~="inspired","old page labels survived")
                if label.hint.word=="nomenclature" then changed=true end
            end
            assert(changed,"next page words were not processed")
            plugin:setEnabled(false)
            assert(ui.document.configurable.line_spacing==old_spacing,"native line spacing did not restore")
            assert(#plugin.labels==0 and not plugin.auto_task)
            ui.rolling:onGotoViewRel(-1)
            assert(not plugin.auto_task,"disabled mode queued a new scan")
            plugin:saveOption("show_button",false)
            ui:onGesture({ges="tap",pos=require("ui/geometry"):new{x=rect.x+rect.w/2,y=rect.y+rect.h/2}})
            assert(not plugin.controls,"hidden button still opened settings")
            plugin:saveOption("show_button",true)
            local restored=plugin:buttonRect()
            ui:onGesture({ges="tap",pos=require("ui/geometry"):new{x=restored.x+restored.w/2,y=restored.y+restored.h/2}})
            assert(plugin.controls,"restored button did not open settings")
            UIManager:close(plugin.controls)
            print("1 passed, 0 failed; actual ReaderUI button, auto page turn, and disable")
            UIManager:quit()
        end)
    end)
end)
arg={book}
dofile("reader.lua")
