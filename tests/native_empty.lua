-- Actual native OCR and CREngine; empty neighbors must not abort the batch.
require("setupkoenv")
local root=assert(arg[1])
package.path=root.."/wordwise.koplugin/?.lua;"..package.path
G_defaults=require("luadefaults"):open()
G_reader_settings=require("luasettings"):open(os.getenv("KO_HOME").."/settings.reader.lua")
local Device=require("device")
require("document/canvascontext"):init(Device)
local BB,Geom=require("ffi/blitbuffer"),require("ui/geometry")
local OCR,Text=require("wordwise_ocr"),require("wordwise_text")
local width,height=Device.screen:getWidth(),Device.screen:getHeight()
local gray=BB.new(width,height,BB.TYPE_BB8)
gray:paintRect(0,0,width,height,BB.COLOR_WHITE)
local empty=OCR.recognize(gray,root.."/wordwise.koplugin/models",Device.screen:getDPI())
assert(#empty.words==0 and #empty.lines==0,"blank native OCR must return an empty result")
print("1 passed, 0 failed; native blank-page OCR")
local doc=require("document/documentregistry"):openDocument(root.."/tests/fixtures/empty-pages.html")
doc:setupDefaultView();doc:setStatusLineProp(1);doc:setFontSize(44);doc:setInterlineSpacePercent(200)
assert(doc:loadDocument());doc:render()
local View=require("apps/reader/modules/readerview")
local view=setmetatable({document=doc,state={offset=Geom:new{x=0,y=0}},
    visible_area=Geom:new{x=0,y=0,w=width,h=height}},{__index=View})
local count=doc:getPageCount()
assert(count==5,"fixture must contain body, blank, contents, dedication and body; got "..count)
-- Confirm the page is really blank in native rendering, not a mocked nil.
view.state.page=2;view:drawPageView(gray,0,0)
assert(not Text.inkBounds(gray,{x=0,y=0,w=width,h=height}),"blank fixture contains rendered content")
view.state.page=1;view:drawPageView(gray,0,0)
local body=OCR.recognize(gray,root.."/wordwise.koplugin/models",Device.screen:getDPI())
assert(#body.words>0 and #body.lines>0,"normal native OCR stopped recognizing text")
view.state.page=2;view:drawPageView(gray,0,0)
print("1 passed, 0 failed; native non-empty OCR after a blank page")
local Core=require("wordwise_core")
local owner={ui={document=doc},view=view,path=root.."/wordwise.koplugin",threshold=0,
    records=Core.readLevels(root.."/wordwise.koplugin/data/levels.tsv"),
    names=require("wordwise_names").load(root.."/wordwise.koplugin/models/pos")}
local Prefetch=require("wordwise_prefetch")
local UIManager=require("ui/uimanager")
UIManager:show(require("ui/widget/container/widgetcontainer"):new{})
io.stdout:flush() -- Do not duplicate the parent's buffered test output after fork.
Prefetch.start(function() return Prefetch.prepare(owner,{1,2,3,4,5}) end,function(batch)
    assert(doc:getCurrentPage()==2,"background preparation moved the parent cursor")
    assert(#batch==5,"empty page aborted the remaining pages")
    assert(#batch[1].hints>0 and #batch[5].hints>0,"body hints lost around an empty page")
    assert(#batch[2].hints==0 and #batch[2].lines==0,"blank page inherited another page's words")
    assert(batch[3].source=="原文" and #batch[3].lines>0,"contents must use the real text layer")
    assert(batch[4].source=="原文" and #batch[4].lines>0,"sparse dedication must use the real text layer")
    gray:free();doc:close()
    print("1 passed, 0 failed; forked empty/contents/dedication/body batch and isolated cursor")
    UIManager:quit()
end,function(err) error(err) end)
UIManager:run()
